"""
Unified inference orchestrator (Phase 6).

Routes each chat request to the right component:
  1. Safety refusal (regex)                        -> refuse (no generation)
  2. Local LLM available                           -> LLM generates answer,
     with KB context attached when retrieval is relevant (RAG).
  3. Otherwise                                     -> existing retrieval
     engine answers, clearly labeled as retrieval, never as LLM output.

Response `source` values callers can rely on:
  - "llm"                      : generated by the local LLM alone
  - "llm+rag"                  : generated by the local LLM using KB context
  - "conversation_dataset"     : retrieval hit from curated pairs
  - "knowledge_base"           : retrieval hit from the KB
  - "safety_filter"            : refusal
  - "fallback"                 : honest "I don't know"

The orchestrator NEVER labels a retrieval result as LLM generation and
never claims a fine-tuned model unless one is actually loaded.
"""

RETRIEVAL_ID = "cyberllm-rag-hybrid-v1"


class UnifiedInference:
    def __init__(self):
        from cyberllm.llm.adapter import get_adapter
        from cyberllm.conversation.engine import get_engine
        from cyberllm.rag.pipeline import retrieve, build_context

        self._adapter = get_adapter()
        self._engine = get_engine()
        self._retrieve = retrieve
        self._build_context = build_context

    # ----------------------------------------------------------- status
    def capabilities(self):
        llm_loaded = self._adapter.is_loaded()
        llm_ok = self._adapter.is_available()
        return {
            "llm": {
                "enabled": self._adapter.enabled,
                "loaded": llm_loaded,
                "available": llm_ok,
                "model_id": self._adapter.model_id if llm_loaded or self._adapter.enabled else None,
                "load_error": self._adapter._load_error,
                "fine_tuned_adapter": self._detect_adapter_weights(),
            },
            "retrieval_engine": {
                "id": RETRIEVAL_ID,
                "records": len(self._engine.records),
                "kb_documents": len(self._engine.kb_documents),
            },
        }

    def _detect_adapter_weights(self):
        from pathlib import Path
        candidates = list((Path(__file__).parents[2] / "models").glob("**/adapter_model.safetensors"))
        return str(candidates[0].relative_to(candidates[0].parents[2])) if candidates else None

    # ------------------------------------------------------------- chat
    def respond(self, message):
        """Return (answer, metadata) for a chat request."""
        message = (message or "").strip()
        if not message:
            return (
                "Please ask a cybersecurity question — for example, "
                "'What is ethical hacking?' or 'How does phishing work?'",
                {"source": "fallback", "confidence": 0.0},
            )

        # 1. Safety gate first — same rules for both paths.
        if self._engine.is_harmful(message):
            return self._engine.respond(message)

        # 2. LLM path (with RAG context when retrieval is relevant).
        if self._adapter.is_available():
            docs = self._retrieve(message)
            context = self._build_context(docs) if docs else ""
            try:
                result = self._adapter.generate(message, context=context or None)
                if result.get("refused"):
                    return result["answer"], {
                        "source": "safety_filter",
                        "confidence": 1.0,
                        "refused": True,
                    }
                answer = result["answer"]
                if answer:
                    meta = {
                        "source": "llm+rag" if docs else "llm",
                        "model_id": result["model_id"],
                        "device": result["device"],
                        "generation_time_s": result["elapsed_s"],
                        "confidence": 0.9 if docs else 0.75,
                        "retrieved_sources": [
                            {k: doc[k] for k in ("doc_id", "title", "source", "score") if doc.get(k)}
                            for doc in docs
                        ] if docs else [],
                        "fine_tuned": self._detect_adapter_weights() is not None,
                    }
                    if docs:
                        meta["note"] = (
                            "Explanation generated by the local LLM using the "
                            "listed knowledge base sources; verify claims against "
                            "the sources where possible.")
                    return answer, meta
                # empty generation -> fall through to retrieval honestly
            except Exception:
                pass  # fall through; never claim LLM answered

        # 3. Retrieval path — always labeled as retrieval.
        answer, meta = self._engine.respond(message)
        return answer, meta


_inference = None


def get_inference():
    global _inference
    if _inference is None:
        _inference = UnifiedInference()
    return _inference
