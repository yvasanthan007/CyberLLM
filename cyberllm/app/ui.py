"""Streamlit operator console for CyberLLM.

A thin client over the FastAPI service: the UI holds no security logic of its
own, so anything it displays came from the API's validated responses. That
means the browser surface inherits the API's input limits, its error typing
and its explicit "unconfigured" reporting for free.

Run with::

    python -m cyberllm.cli app          # API + UI
    streamlit run cyberllm/app/ui.py    # UI only
"""

from __future__ import annotations

import json
import os
from typing import Any

import requests
import streamlit as st

st.set_page_config(
    page_title="CyberLLM Console",
    page_icon=":material/security:",
    layout="wide",
    initial_sidebar_state="expanded",
)

API_BASE = os.environ.get("CYBERLLM_API_URL", "http://127.0.0.1:8000")
API_KEY = os.environ.get("CYBERLLM_API_KEY", "")

DEMO_BANNER = (
    "**Demo mode** - no language model is running. Answers are assembled from "
    "retrieved source records by a template, not generated by a model."
)


@st.cache_data(ttl=20, show_spinner=False)
def api_get(path: str, key: str = "") -> Any:
    """GET a JSON endpoint, returning ``None`` when the API is unreachable."""
    headers = {"X-API-Key": key} if key else {}
    try:
        response = requests.get(f"{API_BASE}{path}", headers=headers, timeout=20)
        response.raise_for_status()
        return response.json()
    except requests.RequestException as exc:
        st.error(f"Cannot reach the API at {API_BASE}: {exc}")
        st.caption("Start it with:  python -m cyberllm.cli app --api")
        return None


@st.cache_data(ttl=20, show_spinner=False)
def api_post(path: str, payload: dict, key: str = "") -> tuple[int, Any]:
    """POST JSON, returning ``(status_code, body)`` without raising."""
    headers = {"X-API-Key": key} if key else {}
    try:
        response = requests.post(f"{API_BASE}{path}", json=payload,
                                 headers=headers, timeout=120)
    except requests.RequestException as exc:
        return 0, {"error": str(exc), "code": "unreachable",
                   "details": {"setup_hint": f"Start the API on {API_BASE}"}}
    try:
        return response.status_code, response.json()
    except ValueError:
        return response.status_code, {"error": response.text[:500], "code": "bad_response"}


def render_error(status: int, body: Any) -> None:
    """Show a typed API error with its setup hint, never a bare failure."""
    if status == 0 or not isinstance(body, dict):
        st.error(str(body))
        return
    st.error(body.get("error", "Request failed"))
    hint = (body.get("details") or {}).get("setup_hint")
    if hint:
        st.info(f"**How to fix:** {hint}")


def sidebar() -> dict[str, Any]:
    """Render navigation and return the selected page."""
    with st.sidebar:
        st.title("CyberLLM")
        health = api_get("/health", API_KEY)
        if health:
            badge = "DEMO" if health.get("demo_mode") else "LIVE"
            if health.get("status") == "ok":
                st.success(f"API healthy - {badge} mode",
                           icon=":material/check_circle:")
            else:
                st.warning(f"API reachable - {badge} mode (degraded)",
                           icon=":material/warning:")
        page = st.radio("Section", [
            "Chat", "Vulnerability lookup", "Intrusion detection",
            "Phishing analysis", "Malware features", "Datasets", "Model metrics",
        ])
        st.divider()
        st.caption("Defensive use only. Classifier outputs are probabilistic "
                   "analyst aids - corroborate with the cited sources.")
    return {"page": page, "health": health}


def page_chat(health: dict[str, Any]) -> None:
    """Cited question answering over the knowledge base."""
    st.header("Cybersecurity AI chat")
    if health and health.get("demo_mode"):
        st.warning(DEMO_BANNER, icon=":material/warning:")

    kb = (health or {}).get("knowledge_base", {})
    if kb and not kb.get("documents"):
        st.info("The knowledge base is empty. Index some data first:\n\n"
                "```\npython -m cyberllm.cli datasets download --all\n"
                "python -m cyberllm.cli rag ingest\n```")

    if "messages" not in st.session_state:
        st.session_state.messages = []

    for message in st.session_state.messages:
        with st.chat_message(message["role"]):
            st.markdown(message["content"])
            if message.get("citations"):
                with st.expander(f"Sources ({len(message['citations'])})"):
                    for cite in message["citations"]:
                        st.markdown(
                            f"- **[{cite['index']}] {cite['title']}** "
                            f"(score {cite['score']:.3f})  \n"
                            f"  {cite.get('source', '')} {cite.get('url', '')}"
                        )

    question = st.chat_input("Ask about a CVE, an ATT&CK technique, or a detection")
    if not question:
        return

    st.session_state.messages.append({"role": "user", "content": question})
    with st.chat_message("user"):
        st.markdown(question)

    with st.chat_message("assistant"):
        with st.spinner("Retrieving and answering..."):
            status, body = api_post("/chat", {"question": question}, API_KEY)
        if status != 200:
            render_error(status, body)
            st.session_state.messages.pop()
            return
        st.markdown(body["answer"])
        if body.get("is_demo"):
            st.caption("Produced by a template in demo mode - not model output.")
        if body.get("weak_evidence"):
            st.warning("Weak retrieval evidence - verify against the primary source.")
        for warning in body.get("injection_warnings", []):
            st.error(f"Prompt-injection attempt neutralised: {warning}")
        st.session_state.messages.append({
            "role": "assistant", "content": body["answer"],
            "citations": body.get("citations", []),
        })


def page_vulnerability() -> None:
    """Look up a CVE from the locally indexed threat intelligence."""
    st.header("CVE / vulnerability lookup")
    st.caption("Served from the local index - this lookup makes no external request.")
    cve = st.text_input("CVE identifier", placeholder="CVE-2021-44228",
                        max_chars=20).strip().upper()
    submitted = st.button("Look up", type="primary")
    if not submitted or not cve:
        return
    with st.spinner("Searching the knowledge base..."):
        response = requests.get(
            f"{API_BASE}/vulnerability/{cve}",
            headers={"X-API-Key": API_KEY} if API_KEY else {}, timeout=20,
        )
    if response.status_code != 200:
        render_error(response.status_code, response.json())
        return
    data = response.json()
    if not data["found"]:
        st.warning(
            f"{data['cve_id']} is not present in the indexed datasets. It may "
            "be new, or the relevant dataset may not be ingested yet - check "
            "the Datasets page.")
        return
    if data["in_kev"]:
        st.error("**CISA KEV** - evidence of active exploitation in the wild.")
    if data.get("ransomware_use") == "Yes":
        st.error("**Known to be used in ransomware campaigns.**")
    st.subheader(data.get("title") or data["cve_id"])
    cols = st.columns(4)
    cols[0].metric("CVSS", data["cvss_score"] or "n/a")
    cols[1].metric("Severity", data["cvss_severity"] or "n/a")
    cols[2].metric("Vendor", data["vendor"] or "n/a")
    cols[3].metric("Remediate by", data["due_date"] or "n/a")
    if data.get("description"):
        st.markdown("**Description**")
        st.text(data["description"])
    if data.get("cwes"):
        st.markdown("**Weaknesses**  " + ", ".join(data["cwes"]))
    with st.expander("Sources"):
        for source in data["sources"]:
            st.markdown(f"- {source.get('authority', source['source'])} - "
                        f"[{source['title']}]({source['url']})")
    st.caption(data["disclaimer"])



def page_intrusion(health: dict[str, Any]) -> None:
    """Classify a single authorised flow record."""
    st.header("Network intrusion detection")
    nids = (health or {}).get("intrusion_detection", {})
    if not nids.get("available"):
        st.warning("No trained intrusion-detection model is available.")
        st.code("python -m cyberllm.cli models train --task nids "
                "--data <your-flows.csv>", language="bash")
        return
    if nids.get("is_synthetic"):
        st.warning("The loaded model was trained on **synthetic** data. It "
                    "demonstrates the pipeline and is not a field-accuracy claim.",
                   icon=":material/warning:")

    with st.form("flow"):
        st.caption("Submit an authorised network-flow record. Unknown columns are "
                   "ignored; missing ones are reported with the prediction.")
        raw = st.text_area("Flow record (JSON)", height=170, value=json.dumps({
            "srcip": "10.0.0.5", "dstip": "10.0.0.9", "proto": "tcp",
            "service": "http", "flag": "S", "dur": 0.1,
            "sbytes": 4200, "dbytes": 120, "sttl": 64, "dttl": 3,
        }, indent=2))
        submit = st.form_submit_button("Classify", type="primary")

    if not submit:
        return
    try:
        record = json.loads(raw)
    except json.JSONDecodeError as exc:
        st.error(f"That is not valid JSON: {exc}")
        return
    status, body = api_post("/detect/intrusion", {"records": [record]}, API_KEY)
    if status != 200:
        render_error(status, body)
        return
    prediction = body["predictions"][0]
    cols = st.columns(2)
    cols[0].metric("Prediction", prediction["predicted_class"])
    cols[1].metric("Confidence", f"{prediction['confidence']:.1%}")
    if prediction.get("top_features"):
        st.markdown("**Most influential features**")
        st.dataframe(prediction["top_features"], use_container_width=True)
    if prediction.get("missing_features"):
        st.warning("Missing features (scored as 0): "
                    + ", ".join(prediction["missing_features"][:12]))
    if prediction.get("ignored_columns"):
        st.caption("Ignored: " + ", ".join(prediction["ignored_columns"][:12]))
    st.warning(prediction["disclaimer"], icon=":material/warning:")


def page_phishing(health: dict[str, Any]) -> None:
    """Offline URL scoring."""
    st.header("Phishing URL analysis")
    st.success("Fully offline - the submitted URL is never visited, resolved or "
               "shared with any third party.", icon=":material/security:")
    url = st.text_input("URL to analyse", placeholder="https://example.com/login",
                        max_chars=2048).strip()
    # The button must be rendered unconditionally: `if not url or not st.button(...)`
    # short-circuits and the button never appears until text has been typed,
    # which makes the page impossible to use.
    submitted = st.button("Analyse", type="primary")
    if not submitted or not url:
        return
    status, body = api_post("/phishing/analyse", {"url": url}, API_KEY)
    if status != 200:
        render_error(status, body)
        return
    verdict = "likely phishing" if body["is_phishing"] else "no strong signal"
    colour = "inverse" if body["is_phishing"] else "normal"
    st.metric("Assessment", verdict, delta=None)
    st.progress(min(body["score"], 1.0))
    st.caption(f"Score {body['score']:.3f} against a threshold of "
               f"{body['threshold']:.2f} - method: {body['method']}")
    if body.get("risk_signals"):
        st.markdown("**Why**")
        st.dataframe(body["risk_signals"], use_container_width=True)
    with st.expander("Extracted features"):
        st.json(body["features"])
    st.warning(body["disclaimer"], icon=":material/warning:")
    _ = health


def page_malware(health: dict[str, Any]) -> None:
    """Classify pre-extracted memory features (never executes a sample)."""
    st.header("Malware feature analysis")
    st.error("**No sample is ever executed, loaded or emulated.** Submit only "
             "features extracted elsewhere, in your own sandbox.", icon=":material/security:")
    raw = st.text_area("Feature row (JSON)", height=170, value=json.dumps({
        "PsList": 412, "Threads": 96, "Handles": 2103,
        "Modules": 118, "PsTotalVirtualMemory": 7340032000,
    }, indent=2))
    if not st.button("Classify", type="primary"):
        return
    try:
        features = json.loads(raw)
    except json.JSONDecodeError as exc:
        st.error(f"That is not valid JSON: {exc}")
        return
    status, body = api_post("/malware/analyse", {"features": [features]}, API_KEY)
    if status != 200:
        render_error(status, body)
        return
    verdict = body["predictions"][0]
    st.metric("Predicted family", verdict["predicted_family"])
    st.caption(f"Confidence {verdict['confidence']:.1%} from {verdict['model']}")
    if verdict.get("missing_features"):
        st.warning("Missing features (scored as 0): "
                    + ", ".join(verdict["missing_features"][:12]))
    st.warning(verdict["disclaimer"], icon=":material/warning:")
    _ = health



def page_datasets() -> None:
    """Dataset inventory with acquisition status and manual steps."""
    st.header("Dataset inventory")
    body = api_get("/datasets", API_KEY)
    if not body:
        return
    st.caption("Status is reconciled against real files on disk, not the manifest "
               "alone - a file that was deleted shows as not present.")
    rows = [
        {
            "name": d["name"], "kind": d["kind"], "status": d["status"],
            "access": d["access"], "on disk (MB)": d["actual_size_mb"],
            "published (MB)": d["approx_size_mb"], "files": d["file_count"],
            "preprocess": d["preprocess_status"], "license": d["license"],
        }
        for d in body["datasets"]
    ]
    st.dataframe(rows, use_container_width=True)
    st.caption(f"Summary: {body['summary']}")

    for dataset in body["datasets"]:
        if dataset["access"] == "manual" and not dataset["files"]:
            with st.expander(f"Manual steps - {dataset['name']}"):
                st.markdown(f"**Source:** {dataset['source_url']}  \n"
                            f"**Licence:** {dataset['license']}")
                for step in dataset["manual_steps"]:
                    st.text(step)
        elif dataset.get("error"):
            with st.expander(f"Error - {dataset['name']}"):
                st.error(dataset["error"])


def page_models(health: dict[str, Any]) -> None:
    """Model metrics, provenance and stated limitations."""
    st.header("Model evaluation metrics")
    nids = (health or {}).get("intrusion_detection", {})
    if not nids.get("available"):
        st.warning("No trained model is available.")
        st.code("python -m cyberllm.cli models train --task nids "
                "--data <your-flows.csv>", language="bash")
        return
    if nids.get("is_synthetic"):
        st.warning("**Synthetic training data** - these numbers validate the "
                    "pipeline and are not a real-world benchmark.", icon=":material/warning:")

    st.subheader(nids.get("name", "model"))
    metrics = nids.get("metrics", {})
    cols = st.columns(4)
    cols[0].metric("Accuracy", f"{metrics.get('accuracy', 0):.4f}")
    cols[1].metric("F1 (weighted)", f"{metrics.get('f1_weighted', 0):.4f}")
    cols[2].metric("F1 (macro)", f"{metrics.get('f1_macro', 0):.4f}")
    cols[3].metric("Recall (macro)", f"{metrics.get('recall_macro', 0):.4f}")
    st.caption(f"Dataset: {nids.get('dataset')} | classes: "
               f"{len(nids.get('classes', []))} | features: {nids.get('n_features')}")
    st.info("Read the full model card for the split strategy, seed, library "
            "versions, confusion matrix and limitations:\n\n"
            "```\npython -m cyberllm.cli models evaluate --task nids\n```")

    st.subheader("Knowledge base")
    kb = (health or {}).get("knowledge_base", {})
    st.json({k: v for k, v in kb.items() if k != "embedding"})
    st.caption(f"Embedding: {kb.get('embedding')}")

    if health:
        st.subheader("Known limitations")
        for limitation in health.get("limitations", []):
            st.markdown(f"- {limitation}")


def page_history() -> None:
    """Session-local chat history with an explicit clear control."""
    st.header("Session history")
    st.caption("Held in this browser session only - nothing is persisted server-side "
               "by this console, and clearing it removes it entirely.")
    messages = st.session_state.get("messages", [])
    if not messages:
        st.info("No messages in this session yet.")
        return
    for message in messages:
        with st.chat_message(message["role"]):
            st.markdown(message["content"][:500])
    if st.button("Clear session history", type="secondary"):
        st.session_state.messages = []
        st.rerun()


def main() -> None:
    """Entry point for ``streamlit run cyberllm/app/ui.py``."""
    state = sidebar()
    page = state["page"]
    health = state["health"]
    if page == "Chat":
        page_chat(health)
    elif page == "Vulnerability lookup":
        page_vulnerability()
    elif page == "Intrusion detection":
        page_intrusion(health)
    elif page == "Phishing analysis":
        page_phishing(health)
    elif page == "Malware features":
        page_malware(health)
    elif page == "Datasets":
        page_datasets()
    else:
        page_models(health)


if __name__ == "__main__":
    main()

