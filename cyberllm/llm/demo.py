"""Demo backend: an honest, clearly-labelled stand-in for a real model.

This is **not** a language model and does not pretend to be. It performs no
inference. Instead it restates the retrieved reference material in a fixed
template, so that:

* the application is fully usable (and demonstrable) with no weights, no GPU
  and no API key;
* an operator can never mistake templated text for model reasoning, because
  every response carries ``is_demo=True`` and an unmissable banner.

The template deliberately separates "from the sources" (quoted, cited) from
"general background" (a fixed, clearly generic note) so the epistemic
distinction the platform promises is visible even in demo mode.
"""

from __future__ import annotations

import re
import time
from typing import Any, Sequence

from ..core.config import AppConfig
from .base import SYSTEM_PREAMBLE, GenerationResult, LLMBackend, trim_prompt

BANNER = (
    "**DEMO MODE - no language model is running.** The text below was "
    "assembled from retrieved source records by a template, not generated by "
    "a model. Configure a provider (`CYBERLLM_PROVIDER=transformers|ollama|openai`) "
    "for model-written explanations."
)

#: Matches ``<some_source_content> ... </some_source_content>`` blocks.
#: The matching ``*_notice`` block is deliberately excluded, so only genuine
#: source text is extracted.
_BLOCK_RE = re.compile(r"<(\w+)_content>\s*(.*?)\s*</\1_content>", re.DOTALL)


class DemoBackend(LLMBackend):
    """Retrieval-backed template responder. No inference, no model weights."""

    name = "demo"
    is_real_model = False

    def generate(self, prompt: str, *, system: str = SYSTEM_PREAMBLE,
                 history: Sequence[tuple[str, str]] = (),
                 max_new_tokens: int | None = None) -> GenerationResult:
        started = time.monotonic()
        blocks = [m.group(2).strip() for m in _BLOCK_RE.finditer(prompt)]
        question = _extract_question(prompt)

        if not blocks:
            body = (
                "I could not find anything in the CyberLLM knowledge base that "
                "directly answers this question.\n\n"
                "**Next steps:**\n"
                "- Try rephrasing with a CVE id (e.g. `CVE-2021-44228`) or a MITRE "
                "ATT&CK technique id (e.g. `T1059.001`).\n"
                "- Check that the relevant datasets have been ingested: "
                "`python -m cyberllm.cli rag ingest`.\n"
                "- Note that a demo-mode template is answering regardless of which "
                "provider is configured."
            )
            warnings = ["no_retrieved_context"]
        else:
            excerpts = []
            for index, block in enumerate(blocks[:4], start=1):
                excerpt = " ".join(block.split())
                if len(excerpt) > 420:
                    excerpt = excerpt[:420].rsplit(" ", 1)[0] + "..."
                excerpts.append(f"**[{index}] From the retrieved sources:**\n> {excerpt}")
            body = "\n\n".join(excerpts)
            body += (
                "\n\n**General background (template placeholder, not model "
                "output):** in demo mode no model interprets these records, so "
                "no reasoning, correlation or recommendation is produced. "
                "Everything above is a verbatim excerpt of indexed source data."
            )
            warnings = ["demo_template_response"]

        answer = f"{BANNER}\n\n{body}"
        return GenerationResult(
            text=answer,
            mode=self.name,
            model="none (demo template)",
            provider=self.name,
            prompt_tokens=len(prompt.split()),
            completion_tokens=len(answer.split()),
            elapsed_seconds=time.monotonic() - started,
            is_demo=True,
            warnings=warnings,
        )

    def describe(self) -> dict[str, Any]:
        info = super().describe()
        info["model"] = "none (demo template)"
        info["note"] = "No language model is loaded; responses are templated."
        return info


def _extract_question(prompt: str) -> str:
    """Recover the user's question from the assembled prompt, if possible."""
    marker = "Question:"
    if marker in prompt:
        return prompt.rsplit(marker, 1)[-1].strip()
    lines = [ln for ln in prompt.splitlines() if ln.strip()]
    return lines[-1].strip() if lines else ""


__all__ = ["DemoBackend", "BANNER"]
